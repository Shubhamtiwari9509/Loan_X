from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator


EmploymentStatusType = Literal[
    "Contract", "Salaried", "Self-employed", "Unemployed"
]
MaritalStatusType = Literal["Married", "Single"]
LoanPurposeType = Literal[
    "Business", "Car", "Education", "Home", "Personal"
]
PropertyAreaType = Literal["Rural", "Semiurban", "Urban"]
EducationLevelType = Literal["Graduate", "Not Graduate"]
GenderType = Literal["Female", "Male"]
EmployerCategoryType = Literal[
    "Business", "Government", "MNC", "Private", "Unemployed"
]


class LoanApplicationInput(BaseModel):
    Applicant_Income: float = Field(
        ..., ge=0,
        description="Primary applicant's income",
        examples=[15000.0]
    )
    Coapplicant_Income: float = Field(
        default=0.0, ge=0,
        description="Co-applicant's income",
        examples=[5000.0]
    )
    Employment_Status: EmploymentStatusType = Field(
        ..., description="Employment status", examples=["Salaried"]
    )
    Age: float = Field(
        ..., ge=18, le=100,
        description="Applicant age in years",
        examples=[35.0]
    )
    Marital_Status: MaritalStatusType = Field(
        ..., description="Marital status", examples=["Married"]
    )
    Dependents: float = Field(
        default=0.0, ge=0, le=20,
        description="Number of dependents",
        examples=[1.0]
    )
    Credit_Score: float = Field(
        ..., ge=300, le=900,
        description="Credit score",
        examples=[750.0]
    )
    Existing_Loans: float = Field(
        default=0.0, ge=0, le=50,
        description="Number of active loans",
        examples=[1.0]
    )
    DTI_Ratio: float = Field(
        ..., ge=0.0, le=1.0,
        description="Debt-to-income ratio",
        examples=[0.34]
    )
    Savings: float = Field(
        default=0.0, ge=0,
        description="Total liquid savings",
        examples=[12000.0]
    )
    Collateral_Value: float = Field(
        default=0.0, ge=0,
        description="Estimated collateral value",
        examples=[25000.0]
    )
    Loan_Amount: float = Field(
        ..., gt=0,
        description="Requested loan amount",
        examples=[20000.0]
    )
    Loan_Term: float = Field(
        ..., ge=6, le=360,
        description="Loan repayment term in months",
        examples=[48.0]
    )
    Loan_Purpose: LoanPurposeType = Field(
        ..., description="Purpose of loan", examples=["Home"]
    )
    Property_Area: PropertyAreaType = Field(
        ..., description="Property area", examples=["Urban"]
    )
    Education_Level: EducationLevelType = Field(
        ..., description="Education level", examples=["Graduate"]
    )
    Gender: GenderType = Field(
        ..., description="Gender", examples=["Male"]
    )
    Employer_Category: EmployerCategoryType = Field(
        ..., description="Employer category", examples=["Private"]
    )

    @field_validator("DTI_Ratio", mode="before")
    @classmethod
    def normalize_dti_ratio(cls, v: float) -> float:
        if isinstance(v, (int, float)) and 1.0 < v <= 100.0:
            return float(v) / 100.0
        return float(v)


class PredictionResponse(BaseModel):
    predicted_class: int = Field(
        ..., description="Raw model class output (0 or 1)"
    )
    decision: Literal["Approved", "Rejected"] = Field(
        ..., description="Mapped loan decision"
    )
    approval_probability: float = Field(
        ..., description="Estimated approval probability"
    )
    rejection_probability: float = Field(
        ..., description="Estimated rejection probability"
    )
    model_version: str = Field(
        ..., description="Model artifact identifier"
    )
    disclaimer: str = Field(
        default=(
            "This prediction is an automated statistical estimate "
            "generated by a machine learning model and does not "
            "constitute a guaranteed loan sanction or credit decision "
            "by a financial institution."
        ),
        description="Model disclaimer"
    )


class FeatureContribution(BaseModel):
    feature: str
    value: Any
    contribution: float
    direction: Literal["approval", "rejection", "neutral"]


class ExplanationResponse(BaseModel):
    model_version: str
    explanation_type: str
    output_scale: str
    base_value: float
    output_margin: float
    contribution_sum: float
    contributions: list[FeatureContribution]
    top_factors: list[FeatureContribution]
    disclaimer: str


class HealthResponse(BaseModel):
    status: Literal["healthy", "unhealthy"]
    model_loaded: bool
    model_version: str
    feature_count: int
    categories: dict[str, list[str]]
