import mongoose from "mongoose";

const inputFeaturesSchema = new mongoose.Schema(
  {
    Applicant_Income: { type: Number, required: true },
    Coapplicant_Income: { type: Number, required: true, default: 0 },
    Employment_Status: { type: String, required: true },
    Age: { type: Number, required: true },
    Marital_Status: { type: String, required: true },
    Dependents: { type: Number, required: true, default: 0 },
    Credit_Score: { type: Number, required: true },
    Existing_Loans: { type: Number, required: true, default: 0 },
    DTI_Ratio: { type: Number, required: true },
    Savings: { type: Number, required: true, default: 0 },
    Collateral_Value: { type: Number, required: true, default: 0 },
    Loan_Amount: { type: Number, required: true },
    Loan_Term: { type: Number, required: true },
    Loan_Purpose: { type: String, required: true },
    Property_Area: { type: String, required: true },
    Education_Level: { type: String, required: true },
    Gender: { type: String, required: true },
    Employer_Category: { type: String, required: true }
  },
  { _id: false }
);

const predictionSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true
    },
    inputFeatures: {
      type: inputFeaturesSchema,
      required: true
    },
    predictedClass: {
      type: Number,
      required: true,
      enum: [0, 1]
    },
    decision: {
      type: String,
      required: true,
      enum: ["Approved", "Rejected"]
    },
    approvalProbability: {
      type: Number,
      required: true,
      min: 0,
      max: 1
    },
    rejectionProbability: {
      type: Number,
      required: true,
      min: 0,
      max: 1
    },
    modelVersion: {
      type: String,
      required: true
    },
    disclaimer: {
      type: String,
      default:
        "This prediction is an automated statistical estimate generated by a machine learning model " +
        "and does not constitute a guaranteed loan sanction or credit decision by a financial institution."
    }
  },
  {
    timestamps: true
  }
);

// Compound indexes for user history pagination and admin analytics filtering
predictionSchema.index({ userId: 1, createdAt: -1 });
predictionSchema.index({ decision: 1, createdAt: -1 });

export const Prediction = mongoose.model("Prediction", predictionSchema);
